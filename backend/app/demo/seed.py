"""Seed the demo datasets into the application database."""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Any

from sqlalchemy.orm import Session

from ..core.config import settings
from ..core.logging import get_logger
from ..ingest import store
from . import generator

log = get_logger("demo.seed")

DEMO_FILES = [
    ("retail_orders.csv", "Retail Orders"),
    ("customers.csv", "Customers"),
    ("inventory.csv", "Inventory"),
    ("supplier_deliveries.csv", "Supplier Deliveries"),
]


def ensure_demo_files(destination: Path | None = None) -> dict[str, Any]:
    """Generate the demo CSVs if they are missing."""
    target = Path(destination or settings.demo_dir)
    reference_file = target / "reference_values.json"
    if reference_file.exists() and (target / "retail_orders.csv").exists():
        import json

        return json.loads(reference_file.read_text())
    return generator.write_demo_data(target)


def seed_demo_datasets(db: Session | None, *, force: bool = False) -> list[str]:
    """Ingest the demo datasets (idempotent unless ``force`` is set)."""
    from ..db.base import SessionLocal
    from ..db.models import Dataset

    ensure_demo_files()

    session = db
    owns_session = session is None
    if session is None:
        session = SessionLocal()

    created: list[str] = []
    try:
        for filename, label in DEMO_FILES:
            path = settings.demo_dir / filename
            if not path.exists():
                continue
            raw = path.read_bytes()
            digest = hashlib.sha256(raw).hexdigest()
            existing = (
                session.query(Dataset)
                .filter(Dataset.source_hash == digest, Dataset.deleted_at.is_(None))
                .first()
            )
            if existing and not force:
                continue
            stored = store.create_dataset(
                session,
                raw=raw,
                filename=filename,
                description=(
                    f"Synthetic demo dataset ({label}). Generated by app.demo.generator with "
                    f"seed {generator.SEED}; contains documented edge cases."
                ),
                is_demo=True,
            )
            stored.dataset.name = label
            session.commit()
            created.append(stored.dataset.id)
            log.info("demo.dataset_created", name=label, id=stored.dataset.id)

        bundle = settings.demo_dir / "retail_bundle.xlsx"
        if bundle.exists():
            raw = bundle.read_bytes()
            digest = hashlib.sha256(raw).hexdigest()
            existing = (
                session.query(Dataset)
                .filter(Dataset.source_hash == digest, Dataset.deleted_at.is_(None))
                .first()
            )
            if not existing or force:
                for sheet in ("Orders", "Customers", "Inventory"):
                    stored = store.create_dataset(
                        session,
                        raw=raw,
                        filename="retail_bundle.xlsx",
                        sheet_name=sheet,
                        description=f"Synthetic demo workbook, sheet '{sheet}'.",
                        is_demo=True,
                    )
                    stored.dataset.name = f"Retail Bundle - {sheet}"
                    session.commit()
                    created.append(stored.dataset.id)
    finally:
        if owns_session:
            session.close()
    return created
